class Command(BaseCommand):
    help = 'Seed localities and property listings'

    def handle(self, *args, **options):
        for name, (lat, lng) in LOCALITY_COORDS.items():
            Locality.objects.update_or_create(name=name, defaults={'lat': lat, 'lng': lng})

        for item in SEED_PROPERTIES:
            locality = Locality.objects.get(name=item['locality'])
            data = {**item}
            data.pop('locality')
            Property.objects.update_or_create(
                code=item['code'],
                defaults={**data, 'locality': locality},
            )

        self.stdout.write(
            self.style.SUCCESS(
                f'Seeded {Locality.objects.count()} localities and {Property.objects.count()} properties'
            )
        )
